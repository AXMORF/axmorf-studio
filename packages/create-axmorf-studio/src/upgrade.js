import { createHash, randomUUID } from "node:crypto";
import * as nodeFileSystem from "node:fs/promises";
import { hostname } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";

import {
  RUNTIME_PACKAGE_NAME,
  createSafeProducerConfig,
  mergeWorkspacePackageJson,
} from "./template-values.js";

const DEFAULT_TEMPLATE_ROOT = fileURLToPath(
  new URL("../template", import.meta.url),
);

export const MANAGED_MANIFEST_PATH = ".axmorf/managed.json";
const BACKUP_ROOT = ".axmorf/backups";
const OPERATION_LOCK = ".project-operation.lock";
const RECOVERY_LOCK = ".project-operation.recovery.lock";

/** Product-owned skill directories are mirrored exactly; other skills are untouched. */
export const MIRRORED_DIRECTORIES = Object.freeze([
  ".agents/skills/axmorf-video",
  ".agents/skills/remotion-best-practices",
]);

/** Single files the package owns. User data, Projects and private config are never listed. */
export const MANAGED_FILES = Object.freeze([
  ".env.example",
  ".gitignore",
  "AGENTS.md",
  "CLAUDE.md",
  "GEMINI.md",
  "README.md",
  "remotion.config.ts",
  "src/generated-json.d.ts",
  "src/index.css",
  "src/index.ts",
  "src/runtime/capabilities.ts",
  "src/runtime/styles.ts",
  "tsconfig.json",
]);

/** Regenerated by bootstrap from current Projects, so the template copy is only a seed. */
const BOOTSTRAP_GENERATED = new Set([
  "src/projects/project-registry.generated.ts",
]);

const TEMPLATE_RENAMES = new Map([["gitignore.template", ".gitignore"]]);

const sha256 = (bytes) =>
  `sha256:${createHash("sha256").update(bytes).digest("hex")}`;

const isNotFound = (error) =>
  error !== null && typeof error === "object" && error.code === "ENOENT";

const toPosix = (path) => path.split(sep).join("/");

const listFiles = async (filesystem, root, base = root) => {
  const files = [];
  for (const entry of await filesystem.readdir(root, { withFileTypes: true })) {
    const path = join(root, entry.name);
    if (entry.isSymbolicLink()) {
      throw new Error(
        `Refusing to traverse symbolic link: ${toPosix(relative(base, path))}`,
      );
    }
    if (entry.isDirectory())
      files.push(...(await listFiles(filesystem, path, base)));
    else if (entry.isFile()) files.push(toPosix(relative(base, path)));
    else throw new Error(`Unsupported entry: ${toPosix(relative(base, path))}`);
  }
  return files;
};

const readOptional = async (filesystem, path) => {
  try {
    const status = await filesystem.lstat(path);
    if (status.isSymbolicLink() || !status.isFile()) {
      throw new Error(`Managed path is not a regular file: ${path}`);
    }
    return await filesystem.readFile(path);
  } catch (error) {
    if (isNotFound(error)) return null;
    throw error;
  }
};

const inMirroredDirectory = (path) =>
  MIRRORED_DIRECTORIES.some((directory) => path.startsWith(`${directory}/`));

/**
 * Classifies every template file. An unclassified file fails loudly so a new template
 * entry cannot silently skip upgrades.
 */
export const desiredManagedFiles = async ({
  templateRoot = DEFAULT_TEMPLATE_ROOT,
  filesystem = nodeFileSystem,
} = {}) => {
  const managed = new Map();
  const placeholders = [];
  const managedFiles = new Set(MANAGED_FILES);
  for (const templatePath of await listFiles(filesystem, templateRoot)) {
    const path = TEMPLATE_RENAMES.get(templatePath) ?? templatePath;
    if (inMirroredDirectory(path) || managedFiles.has(path)) {
      managed.set(
        path,
        await filesystem.readFile(join(templateRoot, templatePath)),
      );
    } else if (path.endsWith("/.gitkeep")) {
      placeholders.push(path);
    } else if (!BOOTSTRAP_GENERATED.has(path)) {
      throw new Error(`Template file has no upgrade classification: ${path}`);
    }
  }
  managed.set(
    "producer.config.example.json",
    Buffer.from(`${JSON.stringify(createSafeProducerConfig(), null, 2)}\n`),
  );
  return { managed, placeholders };
};

export const createManagedManifest = ({ managed, creatorVersion }) => ({
  schemaVersion: 1,
  creatorVersion,
  files: Object.fromEntries(
    [...managed.entries()]
      .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
      .map(([path, bytes]) => [path, sha256(bytes)]),
  ),
});

const readManifest = async (filesystem, root) => {
  const bytes = await readOptional(
    filesystem,
    join(root, MANAGED_MANIFEST_PATH),
  );
  if (bytes === null) return null;
  const manifest = JSON.parse(bytes.toString("utf8"));
  if (manifest?.schemaVersion !== 1 || typeof manifest.files !== "object") {
    throw new Error(`${MANAGED_MANIFEST_PATH} is not a supported manifest.`);
  }
  return manifest;
};

const assertWorkspace = (manifest) => {
  if (manifest?.axmorf?.workspaceVersion !== 1) {
    throw new Error(
      "The target is not an AXMORF Studio Workspace (axmorf.workspaceVersion 1).",
    );
  }
  if (typeof manifest.dependencies?.[RUNTIME_PACKAGE_NAME] !== "string") {
    throw new Error(
      `The Workspace does not depend on ${RUNTIME_PACKAGE_NAME}.`,
    );
  }
};

const assertNoActiveOperation = async (filesystem, root) => {
  for (const lock of [OPERATION_LOCK, RECOVERY_LOCK]) {
    try {
      await filesystem.lstat(join(root, lock));
    } catch (error) {
      if (isNotFound(error)) continue;
      throw error;
    }
    throw new Error(
      `A Project operation is active (${lock}); wait for it to finish before upgrading.`,
    );
  }
};

/** Computes the upgrade without writing anything. */
export const planWorkspaceUpgrade = async ({
  root,
  runtimePackage,
  creatorVersion,
  templateRoot,
  filesystem = nodeFileSystem,
}) => {
  const packageBytes = await readOptional(
    filesystem,
    join(root, "package.json"),
  );
  if (packageBytes === null) throw new Error("The target has no package.json.");
  const currentPackage = JSON.parse(packageBytes.toString("utf8"));
  assertWorkspace(currentPackage);
  const { managed, placeholders } = await desiredManagedFiles({
    templateRoot,
    filesystem,
  });
  const previous = await readManifest(filesystem, root);

  const writes = [];
  const removals = [];
  const localChanges = [];
  const recordLocalChange = (path, bytes) => {
    const recorded = previous?.files?.[path];
    if (recorded !== undefined && recorded !== sha256(bytes))
      localChanges.push(path);
  };
  for (const [path, bytes] of managed) {
    const current = await readOptional(filesystem, join(root, path));
    if (current !== null && current.equals(bytes)) continue;
    if (current !== null) recordLocalChange(path, current);
    writes.push({ path, kind: current === null ? "create" : "update" });
  }
  const stale = new Set();
  for (const directory of MIRRORED_DIRECTORIES) {
    let present = [];
    try {
      present = await listFiles(filesystem, join(root, directory), root);
    } catch (error) {
      if (!isNotFound(error)) throw error;
    }
    for (const path of present) if (!managed.has(path)) stale.add(path);
  }
  for (const path of Object.keys(previous?.files ?? {})) {
    if (!managed.has(path)) stale.add(path);
  }
  for (const path of [...stale].sort()) {
    const current = await readOptional(filesystem, join(root, path));
    if (current === null) continue;
    recordLocalChange(path, current);
    removals.push(path);
  }
  const missingPlaceholders = [];
  for (const path of placeholders) {
    if ((await readOptional(filesystem, join(root, path))) === null)
      missingPlaceholders.push(path);
  }

  const nextPackage = mergeWorkspacePackageJson(currentPackage, runtimePackage);
  const nextPackageBytes = Buffer.from(
    `${JSON.stringify(nextPackage, null, 2)}\n`,
  );
  return {
    managed,
    writes,
    removals,
    placeholders: missingPlaceholders,
    localChanges: localChanges.sort(),
    legacyWithoutManifest: previous === null,
    packageChanged: !packageBytes.equals(nextPackageBytes),
    currentPackageBytes: packageBytes,
    nextPackageBytes,
    runtime: {
      from: currentPackage.dependencies[RUNTIME_PACKAGE_NAME],
      to: runtimePackage,
    },
    manifest: createManagedManifest({ managed, creatorVersion }),
  };
};

const writeAtomic = async (filesystem, path, bytes) => {
  await filesystem.mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.axmorf-upgrade-${randomUUID()}`;
  await filesystem.writeFile(temporary, bytes);
  await filesystem.rename(temporary, path);
};

const summarize = (plan, extra) => ({
  workspace: extra.root,
  runtime: plan.runtime,
  created: plan.writes
    .filter(({ kind }) => kind === "create")
    .map(({ path }) => path),
  updated: plan.writes
    .filter(({ kind }) => kind === "update")
    .map(({ path }) => path),
  removed: plan.removals,
  placeholders: plan.placeholders,
  packageJsonChanged: plan.packageChanged,
  localChanges: plan.localChanges,
  legacyWithoutManifest: plan.legacyWithoutManifest,
  ...extra.fields,
});

/**
 * Upgrades product-managed Workspace files and the runtime package in place. Every replaced
 * or removed file is backed up first; a failed install, bootstrap or doctor restores them.
 */
export const upgradeWorkspace = async (
  {
    cwd,
    target = ".",
    install = true,
    dryRun = false,
    runtimePackage,
    creatorVersion,
  },
  {
    filesystem = nodeFileSystem,
    runCommand,
    templateRoot,
    progress = (value) => process.stderr.write(value),
    now = () => new Date(),
  } = {},
) => {
  const root = await filesystem.realpath(resolve(cwd, target));
  await assertNoActiveOperation(filesystem, root);
  const plan = await planWorkspaceUpgrade({
    root,
    runtimePackage,
    creatorVersion,
    templateRoot,
    filesystem,
  });
  if (dryRun) {
    return summarize(plan, {
      root,
      fields: { status: "workspace-upgrade-planned" },
    });
  }
  if (install && typeof runCommand !== "function") {
    throw new Error("A command runner is required.");
  }

  // Hold the same exclusive lock Project operations use, in a compatible format.
  const lockPath = join(root, OPERATION_LOCK);
  const lock = await filesystem.open(lockPath, "wx", 0o600);
  try {
    await lock.writeFile(
      `${JSON.stringify({
        schemaVersion: 2,
        ownerId: "workspace-upgrade",
        token: randomUUID(),
        process: {
          hostname: hostname(),
          pid: process.pid,
          instanceId: randomUUID(),
        },
      })}\n`,
    );
  } finally {
    await lock.close();
  }

  const stamp = now().toISOString().replace(/[:.]/gu, "-");
  const backupRoot = join(root, BACKUP_ROOT, stamp);
  const backedUp = [];
  const created = [];
  try {
    const backup = async (path) => {
      const bytes = await readOptional(filesystem, join(root, path));
      if (bytes === null) return;
      await writeAtomic(filesystem, join(backupRoot, path), bytes);
      backedUp.push(path);
    };
    for (const path of [
      "package.json",
      "package-lock.json",
      MANAGED_MANIFEST_PATH,
      ...plan.writes
        .filter(({ kind }) => kind === "update")
        .map(({ path }) => path),
      ...plan.removals,
    ]) {
      await backup(path);
    }
    for (const { path, kind } of plan.writes) {
      await writeAtomic(filesystem, join(root, path), plan.managed.get(path));
      if (kind === "create") created.push(path);
    }
    for (const path of plan.placeholders) {
      await writeAtomic(filesystem, join(root, path), Buffer.alloc(0));
      created.push(path);
    }
    for (const path of plan.removals) await filesystem.rm(join(root, path));
    await writeAtomic(
      filesystem,
      join(root, "package.json"),
      plan.nextPackageBytes,
    );
    await writeAtomic(
      filesystem,
      join(root, MANAGED_MANIFEST_PATH),
      Buffer.from(`${JSON.stringify(plan.manifest, null, 2)}\n`),
    );
    if (!backedUp.includes(MANAGED_MANIFEST_PATH))
      created.push(MANAGED_MANIFEST_PATH);

    if (install) {
      // bootstrap needs the operation lock free; release it before handing over to the runtime.
      await filesystem.rm(lockPath);
      for (const [stage, command, args] of [
        ["install", "install", []],
        ["bootstrap", "run", ["--silent", "bootstrap"]],
        ["doctor", "run", ["--silent", "doctor"]],
      ]) {
        progress(`[axmorf] upgrade ${stage}: starting\n`);
        await runCommand(command, args, { cwd: root });
        progress(`[axmorf] upgrade ${stage}: complete\n`);
      }
    }
  } catch (error) {
    progress("[axmorf] upgrade failed; restoring backed-up files\n");
    for (const path of created) {
      await filesystem.rm(join(root, path), { force: true });
    }
    for (const path of backedUp) {
      await writeAtomic(
        filesystem,
        join(root, path),
        await filesystem.readFile(join(backupRoot, path)),
      );
    }
    let reinstall = "skipped";
    if (install) {
      try {
        await runCommand("install", [], { cwd: root });
        reinstall = "restored";
      } catch {
        reinstall = "failed";
      }
    }
    throw new Error(
      `Workspace upgrade failed and managed files were restored from ${toPosix(relative(root, backupRoot))} (dependency reinstall: ${reinstall}). ${error instanceof Error ? error.message : String(error)}`,
      { cause: error },
    );
  } finally {
    await filesystem.rm(lockPath, { force: true });
  }

  return summarize(plan, {
    root,
    fields: {
      status: install ? "workspace-upgraded" : "workspace-files-upgraded",
      ready: install,
      backup:
        backedUp.length === 0 ? null : toPosix(relative(root, backupRoot)),
    },
  });
};
